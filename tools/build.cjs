'use strict';
const fs = require('node:fs');
const path = require('node:path');
const crypto = require('node:crypto');
const root = path.resolve(__dirname, '..');
const {packageDirectory} = require('../vendor/token-monitor-0.86.0/src/electron/plugins/package.js');
const plugin = path.join(root, 'plugin');
const packed = packageDirectory(plugin);
const version = packed.rawManifest.version;
const release = path.join(root, 'delivery', `v${version}`);
fs.mkdirSync(release, {recursive: true});
const output = path.join(release, `three-workflow-monitor-${version}.tmplugin`);
fs.writeFileSync(output, packed.bytes, {flag: 'wx'});
const files = ['manifest.json', ...packed.rawManifest.files];
fs.mkdirSync(path.join(release, 'source'), {recursive: true});
for (const file of files) fs.copyFileSync(path.join(plugin, file), path.join(release, 'source', file), fs.constants.COPYFILE_EXCL);
const receipt = {schema: 'workflow-release/1', version, hostVersion: '0.86.0', builtAt: new Date().toISOString(), package: path.basename(output), sha256: packed.hash, bytes: packed.bytes.length, files: Object.fromEntries(files.map(f => [f, crypto.createHash('sha256').update(fs.readFileSync(path.join(plugin, f))).digest('hex')]))};
fs.writeFileSync(path.join(release, 'release.json'), JSON.stringify(receipt, null, 2), {flag: 'wx'});
console.log(JSON.stringify({output, ...receipt}, null, 2));
